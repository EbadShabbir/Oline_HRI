#!/usr/bin/env bash
# Run from submodules/Oline_HRI. Each output directory must be new.
set -euo pipefail
export PYTHONPATH=src:scripts
.venv/bin/python scripts/run_changing_memory.py freeze \
  --draft evaluation/changing_memory_20260914/authored_v2 \
  --review evaluation/changing_memory_20260914/preflight_review_v1.json \
  --output evaluation/changing_memory_20260914/frozen_v1
.venv/bin/python scripts/run_changing_memory.py collect \
  --freeze evaluation/changing_memory_20260914/frozen_v1 \
  --output evaluation/changing_memory_20260914/run_v1
# The invocation above was rejected before inference by the source-hash guard.
# collection_v1.log and invocation_rejection_v1 preserve that rejected invocation.
# A newly added analysis test matched the runtime source glob. Moving that test
# outside the glob restored the exact frozen runtime; no runtime repair occurred.
# Actual primary collection (separate output; never overwrite an existing run):
.venv/bin/python scripts/run_changing_memory.py collect \
  --freeze evaluation/changing_memory_20260914/frozen_v1 \
  --output evaluation/changing_memory_20260914/run_v2
# This is a command history. Reproduction requires NEW output names and a new
# environment freeze if any source, model asset, configuration or host differs.
# Sealed scenario batches were prepared when each pair completed:
experiment_root=evaluation/changing_memory_20260914
for batch in 01 02 03 04 05 06; do
  first_scenario=$(printf 'cm%02d' "$((10#$batch * 2 - 1))")
  second_scenario=$(printf 'cm%02d' "$((10#$batch * 2))")
  python3 "$experiment_root/batch_reviews.py" prepare \
    --freeze "$experiment_root/frozen_v1" --run "$experiment_root/run_v2" \
    --scenarios "$first_scenario" "$second_scenario" \
    --output "$experiment_root/review_batches/batch_$batch"
done
# Two independent assistant contexts read only public packets and wrote the
# original reviewer_a/batch_*.json and reviewer_b/batch_*.json. Those judgments
# cannot be regenerated by a deterministic shell command. All are preserved.
.venv/bin/python "$experiment_root/audit_collection.py" \
  --freeze "$experiment_root/frozen_v1" --run "$experiment_root/run_v2" \
  --output "$experiment_root/collection_audit_v1.json"
.venv/bin/python scripts/analyze_changing_memory.py prepare \
  --freeze "$experiment_root/frozen_v1" --run "$experiment_root/run_v2" \
  --output "$experiment_root/prepared_final_v1"
python3 "$experiment_root/batch_reviews.py" bind \
  --prepared "$experiment_root/prepared_final_v1" \
  --batches "$experiment_root"/review_batches/batch_{01..06} \
  --reviews-a "$experiment_root"/reviewer_a/batch_{01..06}.json \
  --reviews-b "$experiment_root"/reviewer_b/batch_{01..06}.json \
  --output "$experiment_root/bound_reviews_v1"
.venv/bin/python scripts/analyze_changing_memory.py seal-reviews \
  --prepared "$experiment_root/prepared_final_v1" \
  --review-a "$experiment_root/bound_reviews_v1/review_a.json" \
  --review-b "$experiment_root/bound_reviews_v1/review_b.json" \
  --output "$experiment_root/sealed_reviews_v1"
# There were zero disagreements, so no third adjudication was needed.
.venv/bin/python scripts/analyze_changing_memory.py resolve \
  --prepared "$experiment_root/prepared_final_v1" --reviews "$experiment_root/sealed_reviews_v1" \
  --output "$experiment_root/analysis_v1"
.venv/bin/python scripts/analyze_changing_memory_v2.py resolve \
  --prepared "$experiment_root/prepared_final_v1" --reviews "$experiment_root/sealed_reviews_v1" \
  --output "$experiment_root/analysis_v2"
.venv/bin/python "$experiment_root/render_report_tables.py" \
  --analysis "$experiment_root/analysis_v2" --audit "$experiment_root/collection_audit_v1.json" \
  --output "$experiment_root/tables_v1"
# figures_v1 preserves the initial generic caption; figures_v2 corrects only
# that caption. All 288 source data rows are identical.
MPLCONFIGDIR=/tmp/clara-memory-matplotlib python3 "$experiment_root/render_checkpoint_figure.py" \
  --analysis "$experiment_root/analysis_v2" --output "$experiment_root/figures_v2"
